##Therefore, in polymorphism we use the same entities like functions, methods, and even operators to behave differently according to the given context.
#It makes the code easy to use, flexible and extensible.

#The best example is len() function:
print(len("Hello"))  # 5 (length of a string) 
print(len([1, 2, 3]))  # 3 (length of a list)
# Here, at first example, len() function is used to print the length of the given string, ‘hello’
# But , in the second example, len() function is used to print the length of list
